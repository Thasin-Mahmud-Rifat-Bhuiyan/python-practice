# Comparison Operators Assignment

a = 10
b = 5

print("Value of a:", a)
print("Value of b:", b)

# Equal to
print("a == b:", a == b)

# Not equal to
print("a != b:", a != b)

# Greater than
print("a > b:", a > b)

# Less than
print("a < b:", a < b)

# Greater than or equal to
print("a >= b:", a >= b)

# Less than or equal to
print("a <= b:", a <= b)
